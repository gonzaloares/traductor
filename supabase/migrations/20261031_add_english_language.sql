-- English learning track. Existing French rows retain language = 'fr', including their SRS.
-- The legacy reference_french and context_fr column names remain for API compatibility;
-- their values hold English text when language = 'en'.
ALTER TABLE public.sentences
  ADD COLUMN IF NOT EXISTS language TEXT NOT NULL DEFAULT 'fr' CHECK (language IN ('fr','en'));
ALTER TABLE public.practice_scores
  ADD COLUMN IF NOT EXISTS language TEXT NOT NULL DEFAULT 'fr' CHECK (language IN ('fr','en'));
ALTER TABLE public.orthography_words
  ADD COLUMN IF NOT EXISTS language TEXT NOT NULL DEFAULT 'fr' CHECK (language IN ('fr','en'));
ALTER TABLE public.mini_exams
  ADD COLUMN IF NOT EXISTS language TEXT NOT NULL DEFAULT 'fr' CHECK (language IN ('fr','en'));

-- The same Spanish prompt can be practised in both languages independently.
DROP INDEX IF EXISTS public.sentences_unique_level_spanish;
CREATE UNIQUE INDEX IF NOT EXISTS sentences_unique_language_level_spanish
  ON public.sentences(language, level, spanish_text);
CREATE INDEX IF NOT EXISTS sentences_language_review_idx
  ON public.sentences(language, level, next_review_at, mastery_score);
CREATE INDEX IF NOT EXISTS practice_scores_language_date_idx
  ON public.practice_scores(language, created_at, practice_id);
CREATE INDEX IF NOT EXISTS mini_exams_language_started_idx
  ON public.mini_exams(language, started_at DESC);

-- The same misspelled token may occur in both languages without combining progress.
ALTER TABLE public.orthography_words
  DROP CONSTRAINT IF EXISTS orthography_words_word_key_key;
ALTER TABLE public.orthography_words
  ADD CONSTRAINT orthography_words_language_word_key_unique UNIQUE (language, word_key);
CREATE INDEX IF NOT EXISTS orthography_words_language_review_idx
  ON public.orthography_words(language, state, next_review_at);

